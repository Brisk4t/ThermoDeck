/* Generates gen/icon_data.c: the Material Design Icons listed in tools/mdi_icons.txt as
 * 8-bit alpha bitmaps at 24 and 36 px. Built and run for the host by the Makefile:
 *
 *   gen_icons <mdi dir with materialdesignicons-webfont.ttf + _variables.scss> <icon list> > gen/icon_data.c
 *
 * Glyph offsets are relative to the top-left of the icon's square (so an icon can be
 * centered without knowing its shape). Names are sorted for binary search.
 */
#include <math.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define STB_TRUETYPE_IMPLEMENTATION
#include "stb_truetype.h"

static const int SIZES[] = {24, 36};
#define N_SIZES   2
#define MAX_ICONS 1024

static char *read_file(const char *path, long *len)
{
    FILE *f = fopen(path, "rb");
    if (!f) {
        perror(path);
        exit(1);
    }
    fseek(f, 0, SEEK_END);
    long n = ftell(f);
    fseek(f, 0, SEEK_SET);
    char *d = malloc((size_t)n + 1);
    if (!d || fread(d, 1, (size_t)n, f) != (size_t)n) {
        perror(path);
        exit(1);
    }
    d[n] = 0;
    fclose(f);
    if (len) *len = n;
    return d;
}

/* Code point of `name` from the "  "name": F0335," lines of _variables.scss, or -1. */
static int lookup_codepoint(const char *scss, const char *name)
{
    char pat[128];
    snprintf(pat, sizeof pat, "\"%s\": ", name);
    const char *p = strstr(scss, pat);
    return p ? (int)strtol(p + strlen(pat), NULL, 16) : -1;
}

static int cmp_str(const void *a, const void *b) { return strcmp(*(char *const *)a, *(char *const *)b); }

int main(int argc, char **argv)
{
    if (argc != 3) {
        fprintf(stderr, "usage: %s <mdi dir> <icon list>\n", argv[0]);
        return 2;
    }
    char path[1024];
    snprintf(path, sizeof path, "%s/_variables.scss", argv[1]);
    char *scss = read_file(path, NULL);
    snprintf(path, sizeof path, "%s/materialdesignicons-webfont.ttf", argv[1]);
    unsigned char *ttf = (unsigned char *)read_file(path, NULL);
    stbtt_fontinfo font;
    if (!stbtt_InitFont(&font, ttf, stbtt_GetFontOffsetForIndex(ttf, 0))) {
        fprintf(stderr, "%s: not a TrueType font\n", path);
        return 1;
    }

    /* icon names: whitespace separated, '#' starts a comment line */
    char *list = read_file(argv[2], NULL);
    char *names[MAX_ICONS];
    int n = 0;
    for (char *line = strtok(list, "\n"); line; line = strtok(NULL, "\n")) {
        if (line[0] == '#') continue;
        for (char *s = line; *s;) {
            while (*s == ' ' || *s == '\t' || *s == '\r') s++;
            if (!*s) break;
            char *e = s;
            while (*e && *e != ' ' && *e != '\t' && *e != '\r') e++;
            if (n < MAX_ICONS) names[n++] = strndup(s, (size_t)(e - s));
            s = e;
        }
    }
    qsort(names, (size_t)n, sizeof names[0], cmp_str);
    for (int i = 0; i < n; i++)
        if (lookup_codepoint(scss, names[i]) < 0) {
            fprintf(stderr, "gen_icons: unknown icon '%s'\n", names[i]);
            return 1;
        }

    printf("/* Generated by tools/gen_icons.c from tools/mdi_icons.txt -- do not edit.\n"
           " * Material Design Icons (Apache License 2.0): see third_party/mdi/LICENSE */\n");
    printf("#include \"gfx/icons.h\"\n\n");
    printf("const int icon_count = %d;\n", n);
    printf("const char *const icon_names[%d] = {\n", n);
    for (int i = 0; i < n; i++) printf("  \"%s\",\n", names[i]);
    printf("};\n\n");

    int asc, desc, gap;
    stbtt_GetFontVMetrics(&font, &asc, &desc, &gap);
    for (int si = 0; si < N_SIZES; si++) {
        int size = SIZES[si];
        float scale = stbtt_ScaleForMappingEmToPixels(&font, (float)size);
        /* the icon square spans the font's ascent..descent */
        float em_top = (float)asc * scale;
        size_t cap = 1 << 18, len = 0;
        unsigned char *bits = malloc(cap);
        printf("static const glyph_t icons%d_glyphs[%d] = {\n", size, n);
        int (*g)[5] = calloc((size_t)n, sizeof *g);
        for (int i = 0; i < n; i++) {
            int cp = lookup_codepoint(scss, names[i]);
            int w = 0, h = 0, xo = 0, yo = 0;
            unsigned char *bm = stbtt_GetCodepointBitmap(&font, scale, scale, cp, &w, &h, &xo, &yo);
            if (len + (size_t)(w * h) > cap) bits = realloc(bits, cap = (len + (size_t)(w * h)) * 2);
            memcpy(bits + len, bm, (size_t)(w * h));
            g[i][0] = w;
            g[i][1] = h;
            g[i][2] = xo;
            g[i][3] = yo + (int)lroundf(em_top);
            g[i][4] = (int)len;
            len += (size_t)(w * h);
            stbtt_FreeBitmap(bm, NULL);
        }
        for (int i = 0; i < n; i++)
            printf("  {%d,%d,%d,%d,%d,%d},\n", g[i][0], g[i][1], g[i][2], g[i][3], size, g[i][4]);
        printf("};\n");
        printf("static const uint8_t icons%d_bits[%zu] = {\n", size, len);
        for (size_t i = 0; i < len; i += 24) {
            printf("  ");
            for (size_t j = i; j < i + 24 && j < len; j++) printf("%d,", bits[j]);
            printf("\n");
        }
        printf("};\n");
        printf("const font_t icons_%d = { %d, %d, 0, %d, icons%d_glyphs, icons%d_bits };\n\n", size, size, size, size,
               size, size);
        free(g);
        free(bits);
    }
    return 0;
}
