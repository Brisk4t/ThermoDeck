/* Generates gen/font_data.c: anti-aliased 8-bit alpha bitmap fonts for ThermoDeck.
 * Built and run for the host by the Makefile (needs only a C compiler):
 *
 *   gen_font <font dir with DejaVuSans.ttf + DejaVuSans-Bold.ttf> > gen/font_data.c
 *
 * Glyph set: ASCII 32..126 followed by Latin-1 160..255 (191 glyphs per font), the
 * order font_index() in lib/gfx/include/gfx/font.h expects. Pixel sizes are em sizes, as in FreeType.
 */
#include <math.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define STB_TRUETYPE_IMPLEMENTATION
#include "stb_truetype.h"

static const struct {
    const char *name, *file;
    int size;
} FONTS[] = {
    /* order must match the externs in font.h */
    {"font_sm", "DejaVuSans.ttf", 14},       {"font_md", "DejaVuSans.ttf", 18},
    {"font_mdb", "DejaVuSans-Bold.ttf", 18}, {"font_lg", "DejaVuSans-Bold.ttf", 24},
    {"font_xl", "DejaVuSans-Bold.ttf", 32},
};

static unsigned char *read_file(const char *path)
{
    FILE *f = fopen(path, "rb");
    if (!f) {
        perror(path);
        exit(1);
    }
    fseek(f, 0, SEEK_END);
    long n = ftell(f);
    fseek(f, 0, SEEK_SET);
    unsigned char *d = malloc((size_t)n);
    if (!d || fread(d, 1, (size_t)n, f) != (size_t)n) {
        perror(path);
        exit(1);
    }
    fclose(f);
    return d;
}

static int codepoint(int i) { return i < 95 ? 32 + i : 160 + (i - 95); }

int main(int argc, char **argv)
{
    if (argc != 2) {
        fprintf(stderr, "usage: %s <font dir>\n", argv[0]);
        return 2;
    }
    printf("/* Generated by tools/gen_font.c -- do not edit. DejaVu fonts: see third_party/dejavu/LICENSE */\n");
    printf("#include \"gfx/font.h\"\n\n");

    for (size_t fi = 0; fi < sizeof FONTS / sizeof FONTS[0]; fi++) {
        char path[1024];
        snprintf(path, sizeof path, "%s/%s", argv[1], FONTS[fi].file);
        unsigned char *ttf = read_file(path);
        stbtt_fontinfo font;
        if (!stbtt_InitFont(&font, ttf, stbtt_GetFontOffsetForIndex(ttf, 0))) {
            fprintf(stderr, "%s: not a TrueType font\n", path);
            return 1;
        }
        float scale = stbtt_ScaleForMappingEmToPixels(&font, (float)FONTS[fi].size);
        int asc, desc, gap;
        stbtt_GetFontVMetrics(&font, &asc, &desc, &gap);
        int ascent = (int)ceilf(asc * scale), descent = (int)ceilf(-desc * scale);

        size_t cap = 1 << 20, len = 0;
        unsigned char *bits = malloc(cap);
        int glyphs[191][6];
        for (int i = 0; i < 191; i++) {
            int cp = codepoint(i);
            int adv_u, lsb;
            stbtt_GetCodepointHMetrics(&font, cp, &adv_u, &lsb);
            int adv = (int)lroundf(adv_u * scale);
            int w = 0, h = 0, xo = 0, yo = 0;
            unsigned char *bm =
                (cp == 32 || cp == 160) ? NULL : stbtt_GetCodepointBitmap(&font, scale, scale, cp, &w, &h, &xo, &yo);
            /* crop empty rows/columns */
            int top = 0, bot = h, left = w, right = 0;
            while (top < bot) {
                int any = 0;
                for (int x = 0; x < w; x++) any |= bm[top * w + x];
                if (any) break;
                top++;
            }
            while (bot > top) {
                int any = 0;
                for (int x = 0; x < w; x++) any |= bm[(bot - 1) * w + x];
                if (any) break;
                bot--;
            }
            for (int y = top; y < bot; y++)
                for (int x = 0; x < w; x++)
                    if (bm[y * w + x]) {
                        if (x < left) left = x;
                        if (x + 1 > right) right = x + 1;
                    }
            if (top >= bot || right <= left) {
                glyphs[i][0] = glyphs[i][1] = glyphs[i][2] = glyphs[i][3] = 0;
                glyphs[i][4] = adv;
                glyphs[i][5] = (int)len;
            }
            else {
                int gw = right - left, gh = bot - top;
                if (len + (size_t)(gw * gh) > cap) bits = realloc(bits, cap *= 2);
                glyphs[i][0] = gw;
                glyphs[i][1] = gh;
                glyphs[i][2] = xo + left;
                glyphs[i][3] = yo + top;
                glyphs[i][4] = adv;
                glyphs[i][5] = (int)len;
                for (int y = top; y < bot; y++) {
                    memcpy(bits + len, bm + y * w + left, (size_t)gw);
                    len += (size_t)gw;
                }
            }
            if (bm) stbtt_FreeBitmap(bm, NULL);
        }

        const char *n = FONTS[fi].name;
        printf("static const uint8_t %s_bits[%zu] = {\n", n, len);
        for (size_t i = 0; i < len; i += 24) {
            printf("  ");
            for (size_t j = i; j < i + 24 && j < len; j++) printf("%d,", bits[j]);
            printf("\n");
        }
        printf("};\n");
        printf("static const glyph_t %s_glyphs[191] = {\n", n);
        for (int i = 0; i < 191; i++)
            printf("  {%d,%d,%d,%d,%d,%d},\n", glyphs[i][0], glyphs[i][1], glyphs[i][2], glyphs[i][3], glyphs[i][4],
                   glyphs[i][5]);
        printf("};\n");
        printf("const font_t %s = { %d, %d, %d, %d, %s_glyphs, %s_bits };\n\n", n, FONTS[fi].size, ascent, descent,
               ascent + descent, n, n);
        free(bits);
        free(ttf);
    }
    return 0;
}
