#!/usr/bin/env python3
"""Generate src/font_data.c: anti-aliased 8-bit alpha bitmap fonts for ThermoDeck.

Requires Pillow and the DejaVu fonts (fonts-dejavu-core).
Usage: python3 tools/gen_font.py > src/font_data.c

Glyph set: ASCII 32..126 followed by Latin-1 160..255 (191 glyphs per font).
"""
from PIL import ImageFont

DEJAVU = '/usr/share/fonts/truetype/dejavu/'
FONTS = [  # (C name, ttf, pixel size) -- order must match enum in font.h
    ('font_sm', 'DejaVuSans.ttf', 14),
    ('font_md', 'DejaVuSans.ttf', 18),
    ('font_mdb', 'DejaVuSans-Bold.ttf', 18),
    ('font_lg', 'DejaVuSans-Bold.ttf', 24),
    ('font_xl', 'DejaVuSans-Bold.ttf', 32),
]
CODEPOINTS = list(range(32, 127)) + list(range(160, 256))

out = []
w = out.append
w('/* Generated by tools/gen_font.py -- do not edit. DejaVu fonts: see third_party/LICENSE-DejaVu */')
w('#include "font.h"\n')

names = []
for cname, ttf, size in FONTS:
    f = ImageFont.truetype(DEJAVU + ttf, size)
    ascent, descent = f.getmetrics()
    bits = bytearray()
    glyphs = []
    for cp in CODEPOINTS:
        ch = chr(cp)
        adv = int(round(f.getlength(ch)))
        if cp == 32 or cp == 160:
            glyphs.append((0, 0, 0, 0, adv, len(bits)))
            continue
        mask, (ox, oy) = f.getmask2(ch, mode='L', anchor='ls')
        mw, mh = mask.size
        data = bytes(mask)
        # crop empty rows/cols
        rows = [data[y * mw:(y + 1) * mw] for y in range(mh)]
        top = 0
        while top < mh and not any(rows[top]):
            top += 1
        bot = mh
        while bot > top and not any(rows[bot - 1]):
            bot -= 1
        if top >= bot:
            glyphs.append((0, 0, 0, 0, adv, len(bits)))
            continue
        left = min((next(i for i, v in enumerate(r) if v) for r in rows[top:bot] if any(r)))
        right = max((mw - next(i for i, v in enumerate(reversed(r)) if v) for r in rows[top:bot] if any(r)))
        gw, gh = right - left, bot - top
        off = len(bits)
        for y in range(top, bot):
            bits += rows[y][left:right]
        glyphs.append((gw, gh, ox + left, oy + top, adv, off))
    w(f'static const uint8_t {cname}_bits[{len(bits)}] = {{')
    for i in range(0, len(bits), 24):
        w('  ' + ','.join(str(b) for b in bits[i:i + 24]) + ',')
    w('};')
    w(f'static const glyph_t {cname}_glyphs[{len(glyphs)}] = {{')
    for g in glyphs:
        w('  {%d,%d,%d,%d,%d,%d},' % g)
    w('};')
    w(f'const font_t {cname} = {{ {size}, {ascent}, {descent}, {ascent + descent}, {cname}_glyphs, {cname}_bits }};\n')
    names.append(cname)

print('\n'.join(out))
